  const dict = { en, es };
  let current = 'en';
  try {
    const saved = typeof localStorage !== 'undefined' && localStorage.getItem('ncs_lang');
    if (saved === 'es' || saved === 'en') current = saved;
    else if (typeof navigator !== 'undefined' && /^es\b/i.test(navigator.language || '')) current = 'es';
  } catch {
    /* storage unavailable */
  }

  function t(key, vars) {
    let s = (dict[current] && dict[current][key]) ?? dict.en[key] ?? key;
    if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? String(vars[k]) : m));
    return s;
  }

  function apply(root) {
    if (!root || !root.querySelectorAll) return;
    if (root.documentElement) root.documentElement.lang = current;
    for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
    for (const el of root.querySelectorAll('[data-i18n-placeholder]')) el.setAttribute('placeholder', t(el.dataset.i18nPlaceholder));
    for (const el of root.querySelectorAll('[data-i18n-aria-label]')) el.setAttribute('aria-label', t(el.dataset.i18nAriaLabel));
    for (const el of root.querySelectorAll('[data-i18n-title]')) el.setAttribute('title', t(el.dataset.i18nTitle));
    if (root.title !== undefined) root.title = t('appName');
  }

  function setLang(l) {
    current = l === 'es' ? 'es' : 'en';
    try {
      localStorage.setItem('ncs_lang', current);
    } catch {
      /* ignore */
    }
  }

  return { dict, t, apply, setLang, lang: () => current };
